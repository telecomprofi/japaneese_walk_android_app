/**
 * Release signing details live in keystore.properties, which is deliberately not
 * in version control. Generate the key once with:
 *
 *   keytool -genkeypair -v -keystore release.jks -alias japanese-walk \
 *           -keyalg RSA -keysize 4096 -validity 10000
 *
 * then point keystore.properties at it (storeFile / storePassword / keyAlias /
 * keyPassword). Without that file the release build is left unsigned rather than
 * quietly falling back to the debug key.
 */
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}
val releaseStoreFile: String? = keystoreProperties.getProperty("storeFile")

android {
    namespace = "com.telecomprofi.japanesewalk"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.telecomprofi.japanesewalk"
        minSdk = 33
        targetSdk = 35
        versionCode = 1
        versionName = "1.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (releaseStoreFile != null) {
            create("release") {
                storeFile = rootProject.file(releaseStoreFile)
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            isMinifyEnabled = false
        }
        release {
            // Everything that makes a debug build a debug build, off.
            isMinifyEnabled = true
            isShrinkResources = true
            isDebuggable = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            if (releaseStoreFile != null) {
                signingConfig = signingConfigs.getByName("release")
            } else {
                logger.warn(
                    "japanese-walk: no keystore.properties found — the release APK will be " +
                        "UNSIGNED and adb install will reject it. See app/build.gradle.kts."
                )
            }
        }
    }

    // Keep the dependency metadata block out of the shipped APK.
    dependenciesInfo {
        includeInApk = false
        includeInBundle = false
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
    }
    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }
}

